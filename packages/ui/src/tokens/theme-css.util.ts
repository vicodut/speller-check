import { type Palette, paletteVars } from "./palette";

/** shadcn colour token → the palette variable it reads (so it follows light and dark). */
const THEME_COLOURS: ReadonlyArray<readonly [string, string]> = [
  ["background", "background"],
  ["foreground", "foreground"],
  ["card", "card"],
  ["card-foreground", "foreground"],
  ["popover", "card"],
  ["popover-foreground", "foreground"],
  ["muted", "muted"],
  ["muted-foreground", "muted-foreground"],
  ["border", "border"],
  ["input", "border"],
  ["primary", "primary"],
  ["primary-foreground", "primary-foreground"],
  ["ring", "primary"],
  ["destructive", "destructive"],
  ["destructive-foreground", "primary-foreground"],
  ["success", "success"],
  ["success-background", "success-background"],
  ["warning", "warning"],
  ["warning-background", "warning-background"],
];

/**
 * The Tailwind v4 theme shared by the web pages: palette variables on :root (dark follows the
 * system), the shadcn colour tokens mapped onto them, and a @source for the shared components.
 * Pages import it after `@import "tailwindcss"`.
 */
export const themeCss = (light: Palette, dark: Palette): string => `\
/* Generated by packages/ui/scripts/generate.ts from src/tokens/palette.ts. Don't edit. */
@source "./components";

/* \`dark:\` follows the system, like the palette. */
@custom-variant dark (@media (prefers-color-scheme: dark));

:root {
  color-scheme: light dark;
${paletteVars(light, "  ")}
}
@media (prefers-color-scheme: dark) {
  :root {
${paletteVars(dark, "    ")}
  }
}

@theme static inline {
${THEME_COLOURS.map(([name, token]) => `  --color-${name}: var(--gc-${token});`).join("\n")}
}

@layer base {
  body {
    @apply bg-background font-sans text-foreground antialiased;
  }
}
`;
